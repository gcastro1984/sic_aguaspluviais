/**
 * @param {number} water
 * @param {number} rain6h
 * @param {number} forecast1h
 * @returns {{idnivel_alerta: number, cor: string, score_risco: number, razoes: string[]}}
 */
function classifyAlert(water, rain6h, forecast1h) {
  const razoes = [];
  let waterScore = 1;
  let rainScore = 1;
  let forecastScore = 1;

  if (water >= 90) {
    waterScore = 4;
    razoes.push('Nível de água superior ou igual a 90%.');
  } else if (water >= 85) {
    waterScore = 3;
    razoes.push('Nível de água entre 85% e 90%.');
  } else if (water >= 70) {
    waterScore = 2;
    razoes.push('Nível de água entre 70% e 85%.');
  }

  if (rain6h > 60) {
    rainScore = 4;
    razoes.push('Precipitação acumulada superior a 60 mm nas últimas 6 horas.');
  } else if (rain6h >= 41) {
    rainScore = 3;
    razoes.push('Precipitação acumulada entre 41 e 60 mm nas últimas 6 horas.');
  } else if (rain6h >= 30) {
    rainScore = 2;
    razoes.push('Precipitação acumulada entre 30 e 40 mm nas últimas 6 horas.');
  }

  if (forecast1h > 40) {
    forecastScore = 4;
    razoes.push('Precipitação prevista superior a 40 mm na próxima hora.');
  } else if (forecast1h >= 21) {
    forecastScore = 3;
    razoes.push('Precipitação prevista entre 21 e 40 mm na próxima hora.');
  } else if (forecast1h >= 10) {
    forecastScore = 2;
    razoes.push('Precipitação prevista entre 10 e 20 mm na próxima hora.');
  }

  const scores = [waterScore, rainScore, forecastScore];
  const critical = scores.some((s) => s >= 4);
  const high = scores.some((s) => s >= 3);
  const moderateCount = scores.filter((s) => s >= 2).length;

  const score_risco = round(clamp(
    0.45 * water + 0.30 * Math.min(rain6h, 80) + 0.25 * Math.min(forecast1h, 60),
    0,
    100,
  ), 2);

  if (critical) return { idnivel_alerta: 4, cor: 'Vermelho', score_risco, razoes };
  if (high || moderateCount >= 2) return { idnivel_alerta: 3, cor: 'Laranja', score_risco, razoes };
  if (moderateCount >= 1) return { idnivel_alerta: 2, cor: 'Amarelo', score_risco, razoes };

  return {
    idnivel_alerta: 1,
    cor: 'Verde',
    score_risco,
    razoes: ['Valores abaixo dos limites iniciais.'],
  };
}

/**
 * @param {number} h
 * @param {number} totalHours
 * @param {() => number} rng
 * @returns {number}
 */
function rainfallPattern(h, totalHours, rng) {
  const seasonal = 2 + 2 * Math.sin((2 * Math.PI * h) / Math.max(totalHours, 1));
  const baseline = Math.max(0, gaussian(rng, seasonal, 1.5));

  if (rng() < 0.07) return round(baseline + uniform(rng, 8, 35), 2);
  if (rng() < 0.02) return round(baseline + uniform(rng, 35, 60), 2);

  return round(baseline, 2);
}

/**
 * @param {number} vulnerability
 * @param {number} rain6h
 * @param {number} previous
 * @param {() => number} rng
 * @returns {number}
 */
function waterLevelFromRain(vulnerability, rain6h, previous, rng) {
  return round(clamp(
    15 + vulnerability * 3 + rain6h * 0.75 + previous * 0.55 * 0.25 + gaussian(rng, 0, 3.5),
    5,
    100,
  ), 2);
}

