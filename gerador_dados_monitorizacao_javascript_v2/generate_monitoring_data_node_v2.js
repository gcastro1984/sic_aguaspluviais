/**
 * Deterministic pseudo-random generator.
 * @param {number} seed
 * @returns {() => number}
 */
function makeRng(seed) {
  let state = seed >>> 0;
  return () => {
    state += 0x6D2B79F5;
    let x = state;
    x = Math.imul(x ^ (x >>> 15), x | 1);
    x ^= x + Math.imul(x ^ (x >>> 7), x | 61);
    return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
  };
}

/** @param {number} x @param {number} a @param {number} b */
const clamp = (x, a, b) => Math.max(a, Math.min(b, x));

/** @param {number} x @param {number} d */
const round = (x, d = 2) => Math.round(x * 10 ** d) / 10 ** d;

/** @param {() => number} rng @param {number} a @param {number} b */
const uniform = (rng, a, b) => a + (b - a) * rng();

/** @param {() => number} rng @param {number} a @param {number} b */
const randint = (rng, a, b) => Math.floor(uniform(rng, a, b + 1));

/**
 * Gaussian random value with Box-Muller transform.
 * @param {() => number} rng
 * @param {number} mean
 * @param {number} sd
 */
function gaussian(rng, mean = 0, sd = 1) {
  const u1 = Math.max(rng(), Number.EPSILON);
  const u2 = Math.max(rng(), Number.EPSILON);
  return mean + sd * Math.sqrt(-2 * Math.log(u1)) * Math.cos(2 * Math.PI * u2);
}

/**
 * Weighted choice.
 * @template T
 * @param {() => number} rng
 * @param {Array<[T, number]>} options
 * @returns {T}
 */
function weightedChoice(rng, options) {
  const total = options.reduce((acc, [, w]) => acc + w, 0);
  let cursor = rng() * total;

  for (const [value, weight] of options) {
    cursor -= weight;
    if (cursor <= 0) return value;
  }

  return options[options.length - 1][0];
}

/**
 * MySQL-compatible UTC datetime.
 * @param {Date} date
 * @returns {string}
 */
function mysqlDate(date) {
  const p = (x) => String(x).padStart(2, '0');
  return `${date.getUTCFullYear()}-${p(date.getUTCMonth() + 1)}-${p(date.getUTCDate())} ${p(date.getUTCHours())}:${p(date.getUTCMinutes())}:${p(date.getUTCSeconds())}`;
}

/** @param {Date} d @param {number} h */
const addHours = (d, h) => new Date(d.getTime() + h * 3600_000);

/** @param {Date} d @param {number} m */
const addMinutes = (d, m) => new Date(d.getTime() + m * 60_000);

/**
 * Escape CSV value.
 * @param {unknown} value
 * @returns {string}
 */
function csvValue(value) {
  if (value === null || value === undefined) return '';
  const text = String(value);
  return /[",\n\r]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

/**
 * Write rows to CSV.
 * @param {string} filePath
 * @param {Array<Record<string, unknown>>} rows
 */
function writeCsv(filePath, rows) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });

  if (rows.length === 0) {
    fs.writeFileSync(filePath, '', 'utf8');
    return;
  }

  const columns = Object.keys(rows[0]);
  const lines = [
    columns.join(','),
    ...rows.map((row) => columns.map((col) => csvValue(row[col])).join(',')),
  ];

  fs.writeFileSync(filePath, `${lines.join('\n')}\n`, 'utf8');
}

/**
 * Convert a value to a SQL literal.
 * @param {unknown} value
 * @returns {string}
 */
function sqlLiteral(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
}

/**
 * Write MySQL INSERT script.
 * @param {string} filePath
 * @param {Record<string, Array<Record<string, unknown>>>} tables
 */
function writeSql(filePath, tables) {
  const lines = [
    '-- Synthetic data generated by generate_monitoring_data_node_v2.js',
    'SET FOREIGN_KEY_CHECKS = 0;',
    '',
  ];

  for (const [tableName, rows] of Object.entries(tables)) {
    if (rows.length === 0) continue;

    const columns = Object.keys(rows[0]);
    const columnSql = columns.map((c) => `\`${c}\``).join(', ');

    lines.push(`-- Table: ${tableName}`);

    for (const row of rows) {
      const values = columns.map((c) => sqlLiteral(row[c])).join(', ');
      lines.push(`INSERT INTO \`${tableName}\` (${columnSql}) VALUES (${values});`);
    }

    lines.push('');
  }

  lines.push('SET FOREIGN_KEY_CHECKS = 1;', '');
  fs.writeFileSync(filePath, lines.join('\n'), 'utf8');
}

