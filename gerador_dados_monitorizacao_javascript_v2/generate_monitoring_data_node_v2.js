/**
 * Generate all synthetic tables.
 * @param {{days: number, seed: number, start: Date}} cfg
 * @returns {Record<string, Array<Record<string, unknown>>>}
 */
function generateData(cfg) {
  if (!Number.isInteger(cfg.days) || cfg.days <= 0) {
    throw new Error('days must be a positive integer.');
  }

  const rng = makeRng(cfg.seed);
  const totalHours = cfg.days * 24;

  const area_risco = buildAreas();
  const infraestrutura_urbana = buildInfra(area_risco);
  const sensor = buildSensors(infraestrutura_urbana, rng, cfg.start);
  const nivel_alerta = buildNiveis();
  const criterio_alerta = buildCriterios();
  const utilizador = buildUsers();
  const destinatario = buildDestinatarios();
  const { plano_acao, plano_alerta } = buildPlanos();

  const areaById = Object.fromEntries(area_risco.map((a) => [a.idarea_risco, a]));
  const sensorsByInfra = {};
  for (const s of sensor) {
    sensorsByInfra[s.idinfraestrutura_urbana] ??= [];
    sensorsByInfra[s.idinfraestrutura_urbana].push(s);
  }

  const leitura_sensor = [];
  const previsao_meteorologica = [];
  const alerta = [];
  const alerta_evidencia = [];
  const alerta_destinatario = [];
  const notificacao = [];
  const alerta_plano_acao = [];
  const relatorio = [];

  let idleitura_sensor = 1;
  let idprevisao = 1;
  let idalerta = 1;
  let idalerta_evidencia = 1;
  let idnotificacao = 1;
  let idrelatorio = 1;

  const previousWater = Object.fromEntries(
    infraestrutura_urbana.map((i) => [i.idinfraestrutura_urbana, uniform(rng, 15, 35)]),
  );
  const rainHistory = Object.fromEntries(area_risco.map((a) => [a.idarea_risco, []]));

  for (let h = 0; h < totalHours; h += 1) {
    const observed = addHours(cfg.start, h);
    const observedText = mysqlDate(observed);
    const currentWaterByArea = Object.fromEntries(area_risco.map((a) => [a.idarea_risco, []]));
    const rainThisHour = {};

    for (const area of area_risco) {
      const rawRain = rainfallPattern(h, totalHours, rng);
      const rain = round(rawRain * (1 + (area.vulnerabilidade_base - 3) * 0.07), 2);
      rainThisHour[area.idarea_risco] = Math.max(0, rain);

      rainHistory[area.idarea_risco].push(rain);
      while (rainHistory[area.idarea_risco].length > 6) rainHistory[area.idarea_risco].shift();

      const forecast = round(clamp(rain + gaussian(rng, 0, 8) + uniform(rng, -3, 12), 0, 70), 2);

      previsao_meteorologica.push({
        idprevisao,
        idarea_risco: area.idarea_risco,
        fonte: 'IPMA_simulado',
        data_emissao: observedText,
        data_inicio_previsao: observedText,
        data_fim_previsao: mysqlDate(addHours(observed, 1)),
        horizonte_horas: 1,
        precipitacao_prevista_mm: forecast,
        confianca: round(uniform(rng, 0.65, 0.95), 3),
      });
      idprevisao += 1;
    }

    for (const infra of infraestrutura_urbana) {
      const area = areaById[infra.idarea_risco];
      const rain6h = round(rainHistory[area.idarea_risco].reduce((acc, x) => acc + x, 0), 2);
      const water = waterLevelFromRain(area.vulnerabilidade_base, rain6h, previousWater[infra.idinfraestrutura_urbana], rng);
      previousWater[infra.idinfraestrutura_urbana] = water;

      const flow = round(clamp(water * uniform(rng, 0.6, 1.35), 0, 130), 2);

      for (const s of sensorsByInfra[infra.idinfraestrutura_urbana]) {
        if (s.status === 0 && rng() > 0.25) continue;

        const qualidade_dado = s.status === 0 ? 'falha' : (rng() > 0.08 ? 'boa' : 'suspeita');
        const validada = qualidade_dado === 'boa' ? 1 : 0;

        let tipo_variavel;
        let valor;
        let unidade;

        if (s.tipo === 'nivel_agua') {
          tipo_variavel = 'nivel_agua_percentagem';
          valor = water;
          unidade = '%';
        } else if (s.tipo === 'precipitacao') {
          tipo_variavel = 'precipitacao_horaria';
          valor = rainThisHour[area.idarea_risco];
          unidade = 'mm';
        } else {
          tipo_variavel = 'caudal_estimado';
          valor = flow;
          unidade = 'm3/s';
        }

        const row = {
          idleitura_sensor,
          idsensor: s.idsensor,
          tipo_variavel,
          valor,
          unidade,
          data_observacao: observedText,
          data_registo: mysqlDate(addMinutes(observed, randint(rng, 0, 5))),
          qualidade_dado,
          validada,
        };

        leitura_sensor.push(row);

        if (tipo_variavel === 'nivel_agua_percentagem' && validada === 1) {
          currentWaterByArea[area.idarea_risco].push(row);
        }

        idleitura_sensor += 1;
      }
    }

    for (const area of area_risco) {
      const waterRows = currentWaterByArea[area.idarea_risco];
      if (!waterRows.length) continue;

      const maxWaterRow = waterRows.reduce((best, row) => row.valor > best.valor ? row : best, waterRows[0]);
      const water = Number(maxWaterRow.valor);
      const rain6h = round(rainHistory[area.idarea_risco].reduce((acc, x) => acc + x, 0), 2);
      const forecast = previsao_meteorologica.findLast((p) => p.idarea_risco === area.idarea_risco && p.data_emissao === observedText);
      const cls = classifyAlert(water, rain6h, Number(forecast.precipitacao_prevista_mm));

      if (cls.idnivel_alerta === 1 && rng() > 0.08) continue;

      const areaInfra = infraestrutura_urbana.filter((i) => i.idarea_risco === area.idarea_risco);
      const infraAlert = areaInfra.reduce((best, row) => previousWater[row.idinfraestrutura_urbana] > previousWater[best.idinfraestrutura_urbana] ? row : best, areaInfra[0]);

      const descricao = `Alerta ${cls.cor} na área ${area.nome}. `
        + `Nível máximo de água: ${water.toFixed(2)}%. `
        + `Precipitação acumulada 6h: ${rain6h.toFixed(2)} mm. `
        + `Precipitação prevista 1h: ${Number(forecast.precipitacao_prevista_mm).toFixed(2)} mm.`;

      alerta.push({
        idalerta,
        idnivel_alerta: cls.idnivel_alerta,
        idarea_risco: area.idarea_risco,
        idinfraestrutura_urbana: infraAlert.idinfraestrutura_urbana,
        data_alerta: observedText,
        descricao,
        score_risco: cls.score_risco,
        estado: cls.idnivel_alerta >= 3 ? 'ativo' : 'registado',
      });

      alerta_evidencia.push({
        idalerta_evidencia: idalerta_evidencia++,
        idalerta,
        idleitura_sensor: maxWaterRow.idleitura_sensor,
        idprevisao: null,
        tipo_variavel: 'nivel_agua_percentagem',
        valor_usado: water,
        unidade: '%',
        limiar_aplicado: '70/85/90%',
        contribuicao_para_alerta: 'Leitura máxima de nível de água na área.',
      });

      alerta_evidencia.push({
        idalerta_evidencia: idalerta_evidencia++,
        idalerta,
        idleitura_sensor: null,
        idprevisao: null,
        tipo_variavel: 'precipitacao_acumulada_6h',
        valor_usado: rain6h,
        unidade: 'mm',
        limiar_aplicado: '30/41/60 mm',
        contribuicao_para_alerta: 'Precipitação acumulada calculada sobre as últimas 6 horas.',
      });

      alerta_evidencia.push({
        idalerta_evidencia: idalerta_evidencia++,
        idalerta,
        idleitura_sensor: null,
        idprevisao: forecast.idprevisao,
        tipo_variavel: 'precipitacao_prevista_1h',
        valor_usado: Number(forecast.precipitacao_prevista_mm),
        unidade: 'mm',
        limiar_aplicado: '10/21/40 mm',
        contribuicao_para_alerta: 'Previsão meteorológica simulada para a próxima hora.',
      });

      for (const dest of recipientsForLevel(cls.idnivel_alerta, destinatario)) {
        alerta_destinatario.push({ idalerta, iddestinatario: dest.iddestinatario });

        const sendTime = addMinutes(observed, randint(rng, 1, 10));
        const estado = weightedChoice(rng, [['enviada', 0.60], ['confirmada', 0.35], ['falhada', 0.05]]);

        notificacao.push({
          idnotificacao: idnotificacao++,
          idalerta,
          iddestinatario: dest.iddestinatario,
          canal: cls.idnivel_alerta >= 3 ? 'email_sms' : 'email',
          data_envio: mysqlDate(sendTime),
          estado_envio: estado,
          data_confirmacao: estado === 'confirmada' ? mysqlDate(addMinutes(sendTime, randint(rng, 2, 30))) : null,
          mensagem: `${descricao} Medidas recomendadas associadas ao nível ${cls.cor}.`,
          erro_envio: estado === 'falhada' ? 'Erro simulado no envio.' : null,
        });
      }

      for (const plan of plano_alerta.filter((p) => p.idnivel_alerta === cls.idnivel_alerta)) {
        const started = rng() < (cls.idnivel_alerta >= 3 ? 0.85 : 0.50);
        const estado = started ? weightedChoice(rng, [['em_execucao', 0.5], ['concluido', 0.5]]) : 'pendente';
        const startAction = started ? addMinutes(observed, randint(rng, 5, 30)) : null;

        alerta_plano_acao.push({
          idalerta,
          idplano_acao: plan.idplano_acao,
          estado,
          responsavel: 'Operador Municipal',
          data_inicio: startAction ? mysqlDate(startAction) : null,
          data_conclusao: estado === 'concluido' ? mysqlDate(addMinutes(startAction, randint(rng, 30, 180))) : null,
          observacoes: started ? null : 'Ação ainda não iniciada.',
        });
      }

      relatorio.push({
        idrelatorio: idrelatorio++,
        data: mysqlDate(addMinutes(observed, 15)),
        descricao: `Relatório automático do alerta ${cls.cor}. Razões principais: ${cls.razoes.join(' ')} Score de risco: ${cls.score_risco.toFixed(2)}.`,
        idutilizador: utilizador[randint(rng, 0, utilizador.length - 1)].idutilizador,
        idalerta,
      });

      idalerta += 1;
    }
  }

  return {
    area_risco,
    infraestrutura_urbana,
    sensor,
    leitura_sensor,
    previsao_meteorologica,
    nivel_alerta,
    criterio_alerta,
    alerta,
    alerta_evidencia,
    utilizador,
    destinatario,
    alerta_destinatario,
    notificacao,
    plano_acao,
    plano_alerta,
    alerta_plano_acao,
    relatorio,
  };
}

/**
 * Parse CLI arguments.
 * @returns {{days: number, seed: number, output: string, sql: boolean, start: Date}}
 */
function parseArgs() {
  const cfg = {
    days: 14,
    seed: 42,
    output: 'synthetic_data',
    sql: false,
    start: null,
  };

  for (let i = 2; i < process.argv.length; i += 1) {
    const arg = process.argv[i];

    if (arg === '--days') cfg.days = Number.parseInt(process.argv[++i], 10);
    else if (arg === '--seed') cfg.seed = Number.parseInt(process.argv[++i], 10);
    else if (arg === '--output') cfg.output = process.argv[++i];
    else if (arg === '--sql') cfg.sql = true;
    else if (arg === '--start') cfg.start = new Date(process.argv[++i]);
    else if (arg === '--help' || arg === '-h') {
      console.log(`Usage:
  node generate_monitoring_data_node_v2.js --days 14 --output synthetic_data
  node generate_monitoring_data_node_v2.js --days 30 --seed 123 --output synthetic_data --sql
  node generate_monitoring_data_node_v2.js --days 30 --start 2026-01-01T00:00:00Z --output synthetic_data --sql`);
      process.exit(0);
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }

  if (!cfg.start) {
    const now = new Date();
    cfg.start = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()));
  }

  if (!Number.isInteger(cfg.days) || cfg.days <= 0) throw new Error('--days must be a positive integer.');
  if (!Number.isInteger(cfg.seed)) throw new Error('--seed must be an integer.');
  if (Number.isNaN(cfg.start.getTime())) throw new Error('--start must be a valid date.');

  return cfg;
}

/** Main entry point. */
function main() {
  const cfg = parseArgs();
  const tables = generateData(cfg);

  fs.mkdirSync(cfg.output, { recursive: true });

  for (const [tableName, rows] of Object.entries(tables)) {
    writeCsv(path.join(cfg.output, `${tableName}.csv`), rows);
  }

  if (cfg.sql) {
    writeSql(path.join(cfg.output, 'insert_synthetic_data.sql'), tables);
  }

  console.log('Synthetic data generated successfully.');
  console.log(`Output directory: ${path.resolve(cfg.output)}`);
  for (const [tableName, rows] of Object.entries(tables)) {
    console.log(`- ${tableName}: ${rows.length} rows`);
  }
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(`Error: ${error.message}`);
    process.exit(1);
  }
}

